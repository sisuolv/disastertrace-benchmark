class TestCalendarSlotGeneration:
    """Test continuous calendar slot generation."""

    def test_generates_routine_hour_slots(self):
        """Should generate slots at routine TAF hours: 00Z, 06Z, 12Z, 18Z."""
        import sys
        sys.path.insert(0, str(_project / "scripts"))

        from run_transition_census_v17 import generate_continuous_calendar_slots
        from disastertrace.monitoring_v1.targets import utc_us

        # One day calendar
        start = utc_us("2024-01-01T00:00:00Z")
        end = utc_us("2024-01-02T00:00:00Z")
        # No holdout overlap
        holdout_start = utc_us("2025-02-17T00:00:00Z")
        holdout_end = utc_us("2025-02-24T00:00:00Z")

        slots = generate_continuous_calendar_slots(start, end, holdout_start, holdout_end)

        # Hand-derived: 4 stations x 4 routine hours = 16 slots per day
        assert len(slots) == 16, f"Expected 16 slots, got {len(slots)}"

        # Verify all stations are represented
        stations_in_slots = {s.station for s in slots}
        assert stations_in_slots == {"KSFO", "KDEN", "KJFK", "KORD"}

    def test_excludes_holdout_slots(self):
        """Slots overlapping holdout window must be excluded."""
        import sys
        sys.path.insert(0, str(_project / "scripts"))

        from run_transition_census_v17 import generate_continuous_calendar_slots
        from disastertrace.monitoring_v1.targets import utc_us

        # Calendar spanning holdout
        start = utc_us("2025-02-16T00:00:00Z")
        end = utc_us("2025-02-25T00:00:00Z")
        holdout_start = utc_us("2025-02-17T00:00:00Z")
        holdout_end = utc_us("2025-02-24T00:00:00Z")

        slots = generate_continuous_calendar_slots(start, end, holdout_start, holdout_end)

        # Verify no slot overlaps holdout
        for slot in slots:
            # Slot must not overlap [holdout_start, holdout_end)
            overlaps = (slot.validity_start_us < holdout_end and
                       slot.validity_end_us > holdout_start)
            assert not overlaps, f"Slot at {slot.validity_start_us} overlaps holdout"


