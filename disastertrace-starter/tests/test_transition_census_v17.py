class TestChangeClassification:
    """Test change classification logic with synthetic fixtures.

    Uses make_product from test_revision_ledger.py pattern.
    """

    def make_product(
        self,
        *,
        source_id: str,
        station: str = "KSFO",
        issued_at_us: int,
        valid_start_us: int,
        valid_end_us: int,
        amendment_kind: str = "original",
        status: str = "active",
        semantic_content: dict | None = None,
        provider: str | None = None,
        product_series: str = "default",
    ) -> dict:
        """Create a minimal product dict for census testing."""
        from disastertrace.monitoring_v1.targets import canonical_hash

        content = semantic_content if semantic_content is not None else {"body": source_id}

        product = {
            "source_id": source_id,
            "station": station,
            "issued_at": issued_at_us,
            "valid_start": valid_start_us,
            "valid_end": valid_end_us,
            "amendment_kind": amendment_kind,
            "status": status,
            "native_semantics_sha256": canonical_hash(content),
            "semantic_content": content,
            "product_series": product_series,
        }

        if provider:
            product["provider"] = provider

        return product

    def test_amd_classified_correctly(self):
        """AMD (amendment) products must be classified as AMD changes."""
        from disastertrace.revision_v1.ledger import compile_ledger

        hour_us = 3600 * 1_000_000
        base = 1704067200 * 1_000_000

        # Original TAF, then AMD
        products = [
            self.make_product(
                source_id="taf-orig",
                issued_at_us=base,
                valid_start_us=base + hour_us,
                valid_end_us=base + 7 * hour_us,
            ),
            self.make_product(
                source_id="taf-amd",
                issued_at_us=base + 30 * 60 * 1_000_000,  # 30 min later
                valid_start_us=base + hour_us,
                valid_end_us=base + 7 * hour_us,
                amendment_kind="AMD",
                semantic_content={"body": "amended-content"},
            ),
        ]

        ledger = compile_ledger(products)

        # Hand-derived expectation:
        # - taf-orig: new_observation (first in window)
        # - taf-amd: amendment_supersedes (AMD flag, has predecessor)
        kinds = {e["source_id"]: e["kind"] for e in ledger}

        assert kinds["taf-orig"] == "new_observation"
