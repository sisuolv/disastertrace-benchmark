    def test_process_grouping_is_deterministic(self):
        """Same inputs must produce same groups."""
        import sys
        sys.path.insert(0, str(_project / "scripts"))

        from run_transition_census_v17 import assign_process_groups, EvidenceChange

        # Hand-constructed test case:
        # Two changes at same station on same calendar day -> same group
        # One change at different station -> different group
        hour_us = 3600 * 1_000_000
        base_time = 1704067200 * 1_000_000  # 2024-01-01 00:00:00 UTC

        changes = [
            EvidenceChange(
                target_station="KSFO",
                target_validity_start_us=base_time,
                target_validity_end_us=base_time + hour_us,
                change_type="AMD",
                predecessor_source_id="p1",
                current_source_id="c1",
                original_text_sha256="hash1",
                issued_at_us=base_time + hour_us,  # Jan 1 01:00 UTC
                dispute_status="none",
            ),
            EvidenceChange(
                target_station="KSFO",
                target_validity_start_us=base_time,
                target_validity_end_us=base_time + hour_us,
                change_type="COR",
                predecessor_source_id="p2",
                current_source_id="c2",
                original_text_sha256="hash2",
                issued_at_us=base_time + 12 * hour_us,  # Jan 1 12:00 UTC (same day)
                dispute_status="none",
            ),
            EvidenceChange(
                target_station="KDEN",
                target_validity_start_us=base_time,
                target_validity_end_us=base_time + hour_us,
                change_type="AMD",
                predecessor_source_id="p3",
                current_source_id="c3",
                original_text_sha256="hash3",
                issued_at_us=base_time + hour_us,  # Jan 1 01:00 UTC
                dispute_status="none",
            ),
        ]

        # Run twice, should get same result
        groups1 = assign_process_groups(changes.copy())
        groups2 = assign_process_groups(changes.copy())

        assert len(groups1) == len(groups2), "Same inputs must produce same number of groups"

        # Hand-derived expectation with calendar-day grouping:
        # - KSFO changes both on 2024-01-01 -> 1 group
        # - KDEN has 1 change on 2024-01-01 -> 1 group
        # Total: 2 groups (different because different station, same day)
        assert len(groups1) == 2, f"Expected 2 groups, got {len(groups1)}"

        # Verify KSFO has 2 changes in one group (same station, same day)
        ksfo_groups = [gid for gid in groups1 if gid.startswith("KSFO")]
        assert len(ksfo_groups) == 1, "KSFO should have 1 process group (same calendar day)"
        assert len(groups1[ksfo_groups[0]]) == 2, "KSFO group should have 2 changes"

    def test_process_grouping_splits_different_days(self):
        """Changes on different calendar days must be in different groups."""
        import sys
        sys.path.insert(0, str(_project / "scripts"))

        from run_transition_census_v17 import assign_process_groups, EvidenceChange

        hour_us = 3600 * 1_000_000
        day_us = 24 * hour_us
        base_time = 1704067200 * 1_000_000  # 2024-01-01 00:00:00 UTC

        changes = [
            EvidenceChange(
                target_station="KSFO",
                target_validity_start_us=base_time,
                target_validity_end_us=base_time + hour_us,
                change_type="AMD",
                predecessor_source_id="p1",
                current_source_id="c1",
                original_text_sha256="hash1",
                issued_at_us=base_time + 12 * hour_us,  # Jan 1 12:00 UTC
                dispute_status="none",
            ),
            EvidenceChange(
                target_station="KSFO",
                target_validity_start_us=base_time + day_us,  # Different target
                target_validity_end_us=base_time + day_us + hour_us,
                change_type="AMD",
                predecessor_source_id="p2",
                current_source_id="c2",
                original_text_sha256="hash2",
                issued_at_us=base_time + day_us + 6 * hour_us,  # Jan 2 06:00 UTC
                dispute_status="none",
            ),
        ]

        groups = assign_process_groups(changes)

        # Hand-derived expectation: 2 groups (different calendar days)
        assert len(groups) == 2, f"Expected 2 groups (different calendar days), got {len(groups)}"

        # Verify each group has exactly 1 change
        for group_changes in groups.values():
            assert len(group_changes) == 1


