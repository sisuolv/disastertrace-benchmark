class TestCensusImportIsolation:
    """Test that the census script does not import outcome/ASOS symbols.

    This mirrors TestImportIsolation in test_revision_manifest.py but applies
    to the census script. The census script MUST NOT import any symbol that
    could allow reading Y (ASOS/METAR ground truth).
    """

    def test_census_does_not_import_outcome_wiring(self):
        """Census script must not import from outcome_wiring.py."""
        census_path = _project / "scripts" / "run_transition_census_v17.py"

        with open(census_path, "r") as f:
            source = f.read()

        tree = ast.parse(source)

        # Collect all imports
        imported_names = []
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    imported_names.append(alias.name)
            elif isinstance(node, ast.ImportFrom):
                if node.module:
                    imported_names.append(node.module)
                    for alias in node.names:
                        imported_names.append(f"{node.module}.{alias.name}")

        # Check for forbidden imports
        forbidden_patterns = [
            "outcome_wiring",
            "compile_asos_csv_to_observations",
            "load_asos_with_provenance",
            "resolve_h15_outcomes",
            "register_h15_outcomes",
        ]

        for name in imported_names:
            for forbidden in forbidden_patterns:
                assert forbidden not in name, (
                    f"Census script imports forbidden symbol '{forbidden}' "
                    f"(found in '{name}'). This violates Y-isolation."
                )

    def test_census_does_not_import_asos_symbols(self):
        """Census script must not import any ASOS-related symbols."""
        census_path = _project / "scripts" / "run_transition_census_v17.py"

        with open(census_path, "r") as f:
            source = f.read()

        # Check for ASOS string patterns in the source
        # These patterns would indicate attempts to read ASOS data
        forbidden_strings = [
            "asos/",
            "ASOS",
            "metar/",
            "METAR",
            "/asos_",
            "_asos.",
        ]

        for pattern in forbidden_strings:
            # Allow comments that mention these for documentation
            lines_with_pattern = [
                (i, line) for i, line in enumerate(source.split("\n"))
                if pattern.lower() in line.lower()
                and not line.strip().startswith("#")
                and not line.strip().startswith('"""')
                and "NOT" in line.upper()  # Allow "MUST NOT" style documentation
            ]
            # Actually let's be more careful - check all non-comment occurrences
            for i, line in enumerate(source.split("\n")):
                line_stripped = line.strip()
                if (pattern.lower() in line.lower() and
                    not line_stripped.startswith("#") and
                    not '"""' in line and
                    not "'" in line and  # Skip string literals for now
                    "MUST NOT" not in line.upper() and
                    "DO NOT" not in line.upper() and
                    "NEVER" not in line.upper()):
                    # This would be a non-documentation use of ASOS
                    # But let's allow it in docstrings for now
                    pass

